// 根据文本内容查找对应的音频 key
export function getAudioKey(type: string, ...args: string[]): string | null {
  switch (type) {
    case "complete": return "complete";
    case "pause": return "pause";
    case "resume": return "resume";
    case "countdown": return "countdown_" + args[0];
    case "start": {
      const key = "start_" + sanitizeKey(args[0]);
      return key in AUDIO_MAP ? key : null;
    }
    case "exercise": {
      const key = "ex_" + sanitizeKey(args[0]) + "_" + sanitizeKey(args[1]).substring(0, 20);
      return key in AUDIO_MAP ? key : null;
    }
    default: return null;
  }
}

function sanitizeKey(text: string): string {
  return text.replace(/[^\w\u4e00-\u9fff]/g, "_").replace(/_+/g, "_").replace(/^_|_$/g, "").substring(0, 60);
}
